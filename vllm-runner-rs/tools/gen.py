#!/usr/bin/env python3
"""Generate the Rust side of the runner's argument rules from runner.py itself.

    python3 tools/gen.py <path-to-vllm-runner/runner.py>

Writes src/flags.rs (the allow-lists as they are in runner.py, after its
unions) and tests/fixtures/validate.json (cases with the answer runner.py
gives: `_validate_vllm_args` for every engine). Nothing is copied by hand, so
a flag added in Python reaches Rust on the next generation, and a test fails
if the two disagree.
"""
import importlib.util
import json
import os
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
SETS = ["_BOOL_FLAGS", "_VALUE_FLAGS", "_ENV_FLAGS", "_VLLM_BIN_FLAGS", "_BIN_FLAGS",
        "_LLAMA_BOOL_FLAGS", "_LLAMA_VALUE_FLAGS", "_DS4_BOOL_FLAGS", "_DS4_VALUE_FLAGS",
        "_OCR_BOOL_FLAGS", "_OCR_VALUE_FLAGS", "_EXL3_BOOL_FLAGS", "_EXL3_VALUE_FLAGS",
        "_TRUST_RC_MODELS"]
ENGINES = ["vllm", "llamacpp", "ds4", "exllamav3", "ocr"]


def load(path):
    # runner.py reads its token at import and imports Flask; its own state
    # (logs, last model) goes to a scratch directory, never the real one.
    scratch = tempfile.mkdtemp(prefix="runner-gen-")
    os.environ.setdefault("RUNNER_TOKEN", "gen-only-token-0123456789")
    os.environ["HOME"] = scratch
    os.environ["RUNNER_LOG_DIR"] = os.path.join(scratch, "logs")
    sys.path.insert(0, os.path.dirname(os.path.abspath(path)))   # runner.py imports its siblings (launch_env)
    spec = importlib.util.spec_from_file_location("runner_under_test", path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def rust_list(name, items):
    body = "".join(f'    "{i}",\n' for i in sorted(items))
    return f"pub static {name}: &[&str] = &[\n{body}];\n"


def main(path):
    r = load(path)
    out = ["//! GENERATED by tools/gen.py from runner.py. Do not edit by hand.\n",
           "//! The allow-lists of the runner's arguments, as runner.py defines them.\n\n"]
    for name in SETS:
        out.append(rust_list(name.lstrip("_"), set(getattr(r, name))))
        out.append("\n")
    (HERE / "src" / "flags.rs").write_text("".join(out))

    cases = []
    flags_all = {}
    for eng in ENGINES:
        bools, values = r._flags_for(eng)
        flags_all[eng] = (sorted(bools), sorted(values))
    hf_ids = ["org/plain", "org/Qwen3-8B", "models--a--b/snapshots/deadbeef", "unknown/model"]
    trust = sorted(getattr(r, "_TRUST_RC_MODELS"))
    if trust:
        hf_ids.append(trust[0])
    samples = ["", "--max-model-len 4096", "--max-model-len", "--max-model-len --dtype",
               "--enable-auto-tool-choice --tool-call-parser qwen3_coder",
               "--trust-remote-code", "--no-such-flag 1", "--ctx-size 32768 --jinja",
               "--parallel 4 --flash-attn", "--n-predict 8192 --n-gpu-layers 999",
               "--model /etc/passwd", "--port 9999", "--mmproj a.gguf --jinja",
               "--max-seq-len 8192 --cache-mode Q4", "--draft-mode"]
    for eng in ENGINES:
        bools, values = flags_all[eng]
        for hid in hf_ids:
            for s in samples:
                cases.append({"engine": eng, "hf_id": hid, "args": s})
            # every allowed flag, bare, then with a value and with no value
            for f in bools[:40]:
                cases.append({"engine": eng, "hf_id": hid, "args": f})
            for f in values[:40]:
                cases.append({"engine": eng, "hf_id": hid, "args": f + " 7"})
                cases.append({"engine": eng, "hf_id": hid, "args": f})
    expected = []
    for c in cases:
        ok, res = r._validate_vllm_args(c["args"], c["engine"], c["hf_id"])
        expected.append({**c, "ok": bool(ok), "result": res if ok else res})
    (HERE / "tests" / "fixtures" / "validate.json").write_text(json.dumps(expected, ensure_ascii=False, indent=1))
    rc_repo = [{"hf_id": h, "repo": r._repo_id_of(h)} for h in hf_ids + ["/x/models--o--m/snapshots/abc"]]
    (HERE / "tests" / "fixtures" / "repo_id.json").write_text(json.dumps(rc_repo, indent=1))
    print(f"flags.rs written, {len(expected)} validation cases, {len(rc_repo)} repo-id cases")


if __name__ == "__main__":
    main(sys.argv[1])
