#!/usr/bin/env python3
"""Inventory of the portal's HTTP routes, for the Rust migration.

Reads the portal's SOURCE (no import, no container): every route with its
module, methods, access level (public / login / admin), whether it streams
(SSE), the migration phase that takes it over (docs/rust-migration.md) and
where it is served today (Flask, or Rust once its prefix is listed in
migration/rust-routes.txt).

  python3 scripts/routes-inventory.py           # rewrite docs/rust-routes.md
  python3 scripts/routes-inventory.py --check   # fail if that file is stale

A route matching no phase rule is listed as « unassigned »: a route added
during the migration must be given a phase, not slip through.
"""
import ast
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PORTAL = os.path.join(ROOT, 'dgx-portal')
OUT = os.path.join(ROOT, 'docs', 'rust-routes.md')
RUST_LIST = os.path.join(ROOT, 'migration', 'rust-routes.txt')

PHASES = {
    2: 'stateless reads',
    3: 'media',
    4: 'user data',
    5: 'admin',
    6: 'authentication',
    7: 'chat, playground, Support',
}
# First match wins (more specific rules first).
RULES = [
    (r'^/(login|logout|api/oauth2-redirect|api/csrf|api/whoami|api/setup|internal/authcheck|'
     r'webauthn|api/security|api/session)', 6),
    (r'^/(playground|api/playground|support|api/support)', 7),
    (r'^/(admin|api/admin)', 5),
    (r'^/(healthz|api/health|api/home|api/modelhealth|api/latency|api/ranking|system/stats|usage/|'
     r'metrics|api/running-models|api/search|api/models|\.well-known|docs|api/platform|api/branding|api/config|$)', 2),
    (r'^/(api/image|image/|api/video|video/|api/ocr|ocr/|api/voice|voice/|api/transcribe|'
     r'api/model/request)', 3),
    (r'^/(api/memory|api/skills|skills|settings|api/settings|api/account|conversations|c/|'
     r'api/conversations|api/notifications|mcp|api/mcp|keys|api/keys|discord|request|'
     r'api/announcements|api/history|api/discord|api/onboarding|api/pending-count)', 4),
]
GUARDS = {'admin_required': 'admin', 'login_required': 'login'}


def phase_of(rule):
    for pattern, phase in RULES:
        if re.match(pattern, rule):
            return phase
    return None


def rust_prefixes():
    try:
        with open(RUST_LIST, encoding='utf-8') as f:
            return [ln.strip() for ln in f if ln.strip() and not ln.startswith('#')]
    except OSError:
        return []


def routes():
    out = []
    for name in sorted(os.listdir(PORTAL)):
        if not name.endswith('.py'):
            continue
        src = open(os.path.join(PORTAL, name), encoding='utf-8').read()
        for fn in ast.walk(ast.parse(src)):
            if not isinstance(fn, ast.FunctionDef):
                continue
            names = {getattr(d, 'id', getattr(getattr(d, 'func', None), 'attr', getattr(d, 'attr', '')))
                     for d in fn.decorator_list}
            access = next((GUARDS[g] for g in GUARDS if g in names), 'public')
            body = ast.get_source_segment(src, fn) or ''
            streams = 'text/event-stream' in body
            for d in fn.decorator_list:
                if not (isinstance(d, ast.Call) and getattr(d.func, 'attr', '') in ('route', 'get', 'post')):
                    continue
                if not d.args or not isinstance(d.args[0], ast.Constant):
                    continue
                methods = ['POST'] if d.func.attr == 'post' else ['GET']
                for kw in d.keywords:
                    if kw.arg == 'methods':
                        methods = [m.value for m in kw.value.elts]
                rule = d.args[0].value
                out.append({'rule': rule, 'methods': '/'.join(sorted(methods)), 'module': name,
                            'function': fn.name, 'access': access, 'sse': streams,
                            'phase': phase_of(rule)})
    return sorted(out, key=lambda r: (r['phase'] or 99, r['rule'], r['methods']))


def render(items, rust):
    def served(rule, methods):
        # An entry may name one method (`POST /keys`): the route is on Rust for
        # that method only.
        moved = set()
        for entry in rust:
            only, _, prefix = entry.rpartition(' ')
            if rule.startswith(prefix):
                moved |= {only.upper()} if only else set(methods.split('/'))
        mine = set(methods.split('/'))
        if not moved & mine:
            return 'Flask'
        return 'Rust' if mine <= moved else 'Rust (' + '/'.join(sorted(moved & mine)) + ')'
    lines = ['# Portal routes — Rust migration inventory', '',
             'Generated by `scripts/routes-inventory.py` from the portal source; do not edit.',
             'The plan is in [rust-migration.md](rust-migration.md). A prefix moves to Rust by being',
             'listed in `migration/rust-routes.txt`.', '']
    total = len(items)
    on_rust = sum(1 for r in items if served(r['rule'], r['methods']).startswith('Rust'))
    lines += [f'**{total} routes** — {on_rust} served by Rust, {total - on_rust} by Flask.', '',
              '| Phase | Domain | Routes | Streaming | On Rust |', '|---|---|---|---|---|']
    for ph in [*PHASES, None]:
        sub = [r for r in items if r['phase'] == ph]
        if not sub:
            continue
        lines.append(f"| {ph or '—'} | {PHASES.get(ph, '**unassigned**')} | {len(sub)} | "
                     f"{sum(r['sse'] for r in sub)} | {sum(served(r['rule'], r['methods']).startswith('Rust') for r in sub)} |")
    for ph in [*PHASES, None]:
        sub = [r for r in items if r['phase'] == ph]
        if not sub:
            continue
        lines += ['', f"## Phase {ph} — {PHASES[ph]}" if ph else '## Unassigned — give these a phase', '',
                  '| Route | Methods | Access | SSE | Module | Served by |', '|---|---|---|---|---|---|']
        for r in sub:
            lines.append(f"| `{r['rule']}` | {r['methods']} | {r['access']} | {'yes' if r['sse'] else ''} | "
                         f"`{r['module']}` | {served(r['rule'], r['methods'])} |")
    return '\n'.join(lines) + '\n'


def main():
    text = render(routes(), rust_prefixes())
    if '--check' in sys.argv:
        try:
            current = open(OUT, encoding='utf-8').read()
        except OSError:
            current = ''
        if current != text:
            print('✗ docs/rust-routes.md is stale — run: python3 scripts/routes-inventory.py')
            return 1
        if '## Unassigned' in text:
            print('✗ some routes have no migration phase — add a rule in scripts/routes-inventory.py')
            return 1
        print('✓ route inventory up to date, every route has a phase')
        return 0
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write(text)
    print(f'wrote {os.path.relpath(OUT, ROOT)}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
